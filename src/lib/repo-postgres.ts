import { randomUUID } from "node:crypto";
import { Pool, types } from "pg";
import type { PoolClient, QueryResultRow } from "pg";
import { ETAPAS_INICIAIS } from "./etapas-iniciais";
import { chaveDeNome } from "./nomes";
import { ErroUnicidade } from "./repositorio";
import { diferencaEmSegundos } from "./tempo";
import type { ProximoSegmento, Repositorio } from "./repositorio";
import type {
  Etapa,
  FiltroConsulta,
  LinhaApontamento,
  Sessao,
  SessaoAtiva,
  Status,
  Tipo,
  TipoAcesso,
  Usuario,
  UsuarioComSenha,
} from "./tipos";

/**
 * Postgres direto (Neon ou qualquer outro), usado quando `DATABASE_URL` está
 * preenchida. É o caminho da nuvem: na Vercel não há disco para o SQLite.
 *
 * Mesmo esquema e mesmas regras do SQLite. As tabelas são criadas na primeira
 * conexão, então um banco vazio sobe pronto, sem rodar script à mão. Os ids
 * são texto, como no SQLite: um id malformado vindo de uma aba antiga só não
 * encontra nada, em vez de derrubar a consulta com erro de tipo.
 */
const ESQUEMA = `
create table if not exists etapas (
  id         text primary key,
  nome       text not null,
  nome_chave text not null,
  ativa      boolean not null default true
);
create unique index if not exists etapas_nome_chave_unico on etapas (nome_chave);

create table if not exists apontamentos (
  id               text primary key,
  numero           bigint generated by default as identity,
  etapa_id         text not null references etapas(id),
  numero_os        text not null,
  tipo             text not null check (tipo in ('OPERACAO','PAUSA')),
  inicio           timestamptz not null,
  fim              timestamptz not null,
  duracao_segundos integer not null,
  justificativa    text
);
create unique index if not exists apontamentos_numero_unico on apontamentos (numero);
create index if not exists apontamentos_numero_os_idx on apontamentos (numero_os);
create index if not exists apontamentos_inicio_idx    on apontamentos (inicio);
create index if not exists apontamentos_etapa_idx     on apontamentos (etapa_id, numero_os);

create table if not exists sessoes (
  etapa_id        text primary key references etapas(id),
  numero_os       text not null,
  status          text not null check (status in ('EM_ANDAMENTO','PAUSADO')),
  segmento_inicio timestamptz not null,
  motivo          text
);

create table if not exists usuarios (
  id             text primary key,
  nome           text not null,
  nome_chave     text not null,
  tipo           text not null check (tipo in ('GESTOR','VENDEDOR')),
  ativo          boolean not null default true,
  senha_hash     text not null,
  primeiro_login boolean not null default true,
  versao_sessao  integer not null default 0
);
create unique index if not exists usuarios_nome_chave_unico on usuarios (nome_chave);

create table if not exists configuracao (
  chave text primary key,
  valor text not null
);
`;

/** Número qualquer para a trava da criação do esquema; só precisa ser fixo. */
const TRAVA_ESQUEMA = 731_204;

const OID_BIGINT = 20;
const OID_TIMESTAMPTZ = 1184;

/**
 * Datas voltam como texto ISO, no mesmo formato que o SQLite guarda, e os
 * `bigint` (o "#" e as contagens) como número. O resto do sistema não precisa
 * saber de qual banco veio a linha.
 */
const conversores = {
  getTypeParser(oid: number, formato?: "text" | "binary") {
    if (oid === OID_TIMESTAMPTZ) {
      const comoData = types.getTypeParser(OID_TIMESTAMPTZ, "text");
      return (v: string) => (comoData(v) as Date).toISOString();
    }
    if (oid === OID_BIGINT) return (v: string) => Number(v);
    return types.getTypeParser(oid, formato ?? "text");
  },
};

/** Só chave única. Chave estrangeira, CHECK e NOT NULL são outros erros. */
function ehViolacaoUnica(e: unknown): boolean {
  return (e as { code?: string }).code === "23505";
}

interface UsuarioBruto {
  id: string;
  nome: string;
  tipo: TipoAcesso;
  ativo: boolean;
  senha_hash: string;
  primeiro_login: boolean;
  versao_sessao: number;
}

function comoUsuario(u: UsuarioBruto): Usuario {
  return {
    id: u.id,
    nome: u.nome,
    tipo: u.tipo,
    ativo: u.ativo,
    primeiro_login: u.primeiro_login,
    versao_sessao: u.versao_sessao,
  };
}

function comoEtapa(e: { id: string; nome: string; ativa: boolean }): Etapa {
  return { id: e.id, nome: e.nome, ativa: e.ativa };
}

export class RepositorioPostgres implements Repositorio {
  private pool: Pool;
  private preparo: Promise<void> | null = null;

  constructor() {
    this.pool = new Pool({
      connectionString: process.env.DATABASE_URL,
      types: conversores,
      // Função na nuvem: poucas conexões e soltas logo. O pooler do Neon é que
      // segura o volume; aqui só não pode sobrar conexão parada.
      max: 4,
      idleTimeoutMillis: 5_000,
    });
  }

  /**
   * O esquema é preparado uma vez por instância, na primeira chamada. Se
   * falhar (o banco do Neon acordando, por exemplo), a promessa é esquecida e
   * a chamada seguinte tenta de novo, em vez de repetir o mesmo erro sempre.
   */
  private pronto(): Promise<void> {
    this.preparo ??= this.preparar().catch((e) => {
      this.preparo = null;
      throw e;
    });
    return this.preparo;
  }

  /**
   * Cria o esquema e as etapas iniciais, numa transação com trava: várias
   * instâncias da função subindo juntas esperam a vez, e a segunda já
   * encontra tudo pronto. A trava é da transação, não da conexão, para
   * funcionar também pelo pooler do Neon.
   */
  private async preparar(): Promise<void> {
    await this.transacao(async (c) => {
      await c.query("select pg_advisory_xact_lock($1)", [TRAVA_ESQUEMA]);
      await c.query(ESQUEMA);

      const { rows } = await c.query<{ total: number }>("select count(*) as total from etapas");
      if (rows[0].total > 0) return;
      for (const nome of ETAPAS_INICIAIS) {
        await c.query(
          "insert into etapas (id, nome, nome_chave, ativa) values ($1, $2, $3, true) on conflict do nothing",
          [randomUUID(), nome, chaveDeNome(nome)]
        );
      }
    });
  }

  private async transacao<T>(fn: (c: PoolClient) => Promise<T>): Promise<T> {
    const c = await this.pool.connect();
    try {
      await c.query("begin");
      const resultado = await fn(c);
      await c.query("commit");
      return resultado;
    } catch (e) {
      await c.query("rollback").catch(() => {});
      throw e;
    } finally {
      c.release();
    }
  }

  private async linhas<T extends QueryResultRow>(sql: string, valores: unknown[] = []): Promise<T[]> {
    await this.pronto();
    return (await this.pool.query<T>(sql, valores)).rows;
  }

  private async executar(sql: string, valores: unknown[] = []): Promise<void> {
    await this.pronto();
    await this.pool.query(sql, valores);
  }

  // ---- etapas -----------------------------------------------------------

  async listarEtapas(apenasAtivas: boolean): Promise<Etapa[]> {
    const sql = apenasAtivas
      ? "select * from etapas where ativa order by nome"
      : "select * from etapas order by nome";
    return (await this.linhas<Etapa>(sql)).map(comoEtapa);
  }

  async obterEtapa(id: string): Promise<Etapa | null> {
    const [e] = await this.linhas<Etapa>("select * from etapas where id = $1", [id]);
    return e ? comoEtapa(e) : null;
  }

  async criarEtapa(nome: string): Promise<Etapa> {
    const id = randomUUID();
    try {
      await this.executar(
        "insert into etapas (id, nome, nome_chave, ativa) values ($1, $2, $3, true)",
        [id, nome, chaveDeNome(nome)]
      );
    } catch (e) {
      if (ehViolacaoUnica(e)) throw new ErroUnicidade("nome de etapa repetido");
      throw e;
    }
    return { id, nome, ativa: true };
  }

  async renomearEtapa(id: string, nome: string): Promise<void> {
    try {
      await this.executar("update etapas set nome = $1, nome_chave = $2 where id = $3", [
        nome,
        chaveDeNome(nome),
        id,
      ]);
    } catch (e) {
      if (ehViolacaoUnica(e)) throw new ErroUnicidade("nome de etapa repetido");
      throw e;
    }
  }

  async definirAtivaEtapa(id: string, ativa: boolean): Promise<void> {
    await this.executar("update etapas set ativa = $1 where id = $2", [ativa, id]);
  }

  async excluirEtapa(id: string): Promise<void> {
    await this.executar("delete from etapas where id = $1", [id]);
  }

  async contarApontamentosDaEtapa(id: string): Promise<number> {
    const [r] = await this.linhas<{ total: number }>(
      "select count(*) as total from apontamentos where etapa_id = $1",
      [id]
    );
    return r.total;
  }

  // ---- sessões ----------------------------------------------------------

  async obterSessao(etapaId: string): Promise<Sessao | null> {
    const [s] = await this.linhas<Sessao>("select * from sessoes where etapa_id = $1", [etapaId]);
    return s ?? null;
  }

  async listarSessoesAtivas(): Promise<SessaoAtiva[]> {
    return this.linhas<SessaoAtiva>(
      `select s.*, e.nome as etapa_nome
         from sessoes s
         join etapas e on e.id = s.etapa_id
        order by s.segmento_inicio asc`
    );
  }

  async criarSessao(sessao: Sessao): Promise<void> {
    try {
      await this.executar(
        `insert into sessoes (etapa_id, numero_os, status, segmento_inicio, motivo)
         values ($1, $2, $3, $4, $5)`,
        [sessao.etapa_id, sessao.numero_os, sessao.status, sessao.segmento_inicio, sessao.motivo]
      );
    } catch (e) {
      if (ehViolacaoUnica(e)) throw new ErroUnicidade("já existe sessão para esta etapa");
      throw e;
    }
  }

  /**
   * Fecha o segmento aberto e abre o seguinte, ou encerra a sessão quando
   * `proximo` é nulo, numa transação só. A linha da sessão é travada com
   * `for update`: o segundo de dois cliques simultâneos espera, relê o status
   * já mudado e sai sem gravar nada.
   */
  async avancarSegmento(
    etapaId: string,
    statusEsperado: Status,
    fimISO: string,
    proximo: ProximoSegmento | null
  ): Promise<boolean> {
    await this.pronto();
    return this.transacao(async (c) => {
      const { rows } = await c.query<Sessao>(
        "select * from sessoes where etapa_id = $1 for update",
        [etapaId]
      );
      const s = rows[0];
      if (!s || s.status !== statusEsperado) return false;

      const tipo: Tipo = s.status === "EM_ANDAMENTO" ? "OPERACAO" : "PAUSA";

      // O "#" sai da identidade da própria tabela: dois apontamentos gravados
      // ao mesmo tempo não disputam o número.
      await c.query(
        `insert into apontamentos
           (id, etapa_id, numero_os, tipo, inicio, fim, duracao_segundos, justificativa)
         values ($1, $2, $3, $4, $5, $6, $7, $8)`,
        [
          randomUUID(),
          s.etapa_id,
          s.numero_os,
          tipo,
          s.segmento_inicio,
          fimISO,
          diferencaEmSegundos(s.segmento_inicio, fimISO),
          // Justificativa só existe em segmento de pausa.
          tipo === "PAUSA" ? s.motivo : null,
        ]
      );

      // O próximo segmento começa exatamente onde o anterior terminou.
      if (proximo) {
        await c.query(
          "update sessoes set status = $1, segmento_inicio = $2, motivo = $3 where etapa_id = $4",
          [proximo.status, fimISO, proximo.motivo, etapaId]
        );
      } else {
        await c.query("delete from sessoes where etapa_id = $1", [etapaId]);
      }
      return true;
    });
  }

  // ---- apontamentos -----------------------------------------------------

  async revisaoApontamentos(): Promise<number> {
    const [r] = await this.linhas<{ maior: number }>(
      "select coalesce(max(numero), 0) as maior from apontamentos"
    );
    return r.maior;
  }

  async existeApontamento(etapaId: string, numeroOs: string): Promise<boolean> {
    const achou = await this.linhas(
      "select 1 from apontamentos where etapa_id = $1 and numero_os = $2 limit 1",
      [etapaId, numeroOs]
    );
    return achou.length > 0;
  }

  async consultarApontamentos(f: FiltroConsulta): Promise<LinhaApontamento[]> {
    const condicoes: string[] = [];
    const valores: unknown[] = [];
    const param = (v: unknown) => {
      valores.push(v);
      return `$${valores.length}`;
    };

    // OS: busca parcial, sem cadastro prévio (regra 4).
    if (f.os?.trim()) condicoes.push(`a.numero_os like '%' || ${param(f.os.trim())} || '%'`);
    if (f.osExata?.trim()) condicoes.push(`a.numero_os = ${param(f.osExata.trim())}`);
    if (f.etapaId) condicoes.push(`a.etapa_id = ${param(f.etapaId)}`);
    if (f.tipo) condicoes.push(`a.tipo = ${param(f.tipo)}`);
    if (f.deISO) condicoes.push(`a.inicio >= ${param(f.deISO)}`);
    if (f.ateISO) condicoes.push(`a.inicio < ${param(f.ateISO)}`);

    const onde = condicoes.length ? `where ${condicoes.join(" and ")}` : "";

    // Desempate por `numero`, como no SQLite: várias etapas costumam ter o
    // mesmo início, e a ordem precisa ser a mesma a cada consulta.
    return this.linhas<LinhaApontamento>(
      `select a.*, e.nome as etapa_nome
         from apontamentos a
         join etapas e on e.id = a.etapa_id
         ${onde}
        order by a.inicio asc, a.numero asc`,
      valores
    );
  }

  // ---- usuários do painel ------------------------------------------------

  async contarUsuarios(): Promise<number> {
    const [r] = await this.linhas<{ total: number }>("select count(*) as total from usuarios");
    return r.total;
  }

  async listarUsuarios(): Promise<Usuario[]> {
    return (await this.linhas<UsuarioBruto>("select * from usuarios order by nome_chave")).map(
      comoUsuario
    );
  }

  async obterUsuario(id: string): Promise<Usuario | null> {
    const [u] = await this.linhas<UsuarioBruto>("select * from usuarios where id = $1", [id]);
    return u ? comoUsuario(u) : null;
  }

  async obterUsuarioPorNome(nome: string): Promise<UsuarioComSenha | null> {
    // Pela chave: quem cadastrou "João" entra como "JOÃO" ou "joão".
    const [u] = await this.linhas<UsuarioBruto>("select * from usuarios where nome_chave = $1", [
      chaveDeNome(nome),
    ]);
    return u ? { ...comoUsuario(u), senha_hash: u.senha_hash } : null;
  }

  async criarUsuario(nome: string, tipo: TipoAcesso, senhaHash: string): Promise<Usuario> {
    const usuario: Usuario = {
      id: randomUUID(),
      nome,
      tipo,
      ativo: true,
      primeiro_login: true,
      versao_sessao: 0,
    };
    try {
      await this.executar(
        `insert into usuarios (id, nome, nome_chave, tipo, ativo, senha_hash, primeiro_login, versao_sessao)
         values ($1, $2, $3, $4, true, $5, true, 0)`,
        [usuario.id, nome, chaveDeNome(nome), tipo, senhaHash]
      );
    } catch (e) {
      if (ehViolacaoUnica(e)) throw new ErroUnicidade("nome de usuário repetido");
      throw e;
    }
    return usuario;
  }

  async renomearUsuario(id: string, nome: string): Promise<void> {
    try {
      await this.executar("update usuarios set nome = $1, nome_chave = $2 where id = $3", [
        nome,
        chaveDeNome(nome),
        id,
      ]);
    } catch (e) {
      if (ehViolacaoUnica(e)) throw new ErroUnicidade("nome de usuário repetido");
      throw e;
    }
  }

  async definirTipoUsuario(id: string, tipo: TipoAcesso): Promise<void> {
    await this.executar("update usuarios set tipo = $1 where id = $2", [tipo, id]);
  }

  async definirAtivoUsuario(id: string, ativo: boolean): Promise<void> {
    await this.executar(
      "update usuarios set ativo = $1, versao_sessao = versao_sessao + 1 where id = $2",
      [ativo, id]
    );
  }

  async definirSenhaUsuario(id: string, senhaHash: string, primeiroLogin: boolean): Promise<void> {
    await this.executar(
      `update usuarios
          set senha_hash = $1, primeiro_login = $2, versao_sessao = versao_sessao + 1
        where id = $3`,
      [senhaHash, primeiroLogin, id]
    );
  }

  async excluirUsuario(id: string): Promise<void> {
    await this.executar("delete from usuarios where id = $1", [id]);
  }

  // ---- configuração do próprio sistema -----------------------------------

  async obterConfiguracao(chave: string): Promise<string | null> {
    const [r] = await this.linhas<{ valor: string }>(
      "select valor from configuracao where chave = $1",
      [chave]
    );
    return r?.valor ?? null;
  }

  async fixarConfiguracao(chave: string, valor: string): Promise<string> {
    // Grava só se não houver e relê: se duas instâncias sortearem uma chave
    // de sessão ao mesmo tempo, as duas saem com a mesma.
    await this.executar(
      "insert into configuracao (chave, valor) values ($1, $2) on conflict (chave) do nothing",
      [chave, valor]
    );
    const [r] = await this.linhas<{ valor: string }>(
      "select valor from configuracao where chave = $1",
      [chave]
    );
    return r.valor;
  }
}
